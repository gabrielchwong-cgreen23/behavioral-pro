create table if not exists public.store_benchmarks (
  id bigint generated by default as identity primary key,
  store_id text,
  shop_domain text not null,
  historical_session_count integer not null default 0,
  p75_rage_click_count double precision not null default 0,
  p75_cta_idle_15s_count double precision not null default 0,
  p75_policy_page_view_count double precision not null default 0,
  reached_checkout_rate double precision not null default 0,
  purchase_rate double precision not null default 0,
  source text not null default 'manual',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (shop_domain)
);

create index if not exists store_benchmarks_store_id_idx
  on public.store_benchmarks (store_id);
